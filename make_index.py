def summary(path):
    try:
        doc = ast.get_docstring(ast.parse(io.open(path, encoding="utf-8").read())) or ""
    except Exception:
        return ""
    base = os.path.basename(path).lower()
    for ln in (l.strip() for l in doc.splitlines()):
        if not ln or ln.lower() == base or set(ln) <= set("=-_"):
            continue
        return ln[:110]
    return ""


def main():
    seen, out = set(), []
    out.append("# Script Index\n")
    out.append("Auto-generated by `make_index.py` from each script's docstring. "
               "The docstrings are the real documentation — each states a hypothesis, "
               "a prior, and what would falsify it.\n")
    out.append("**Read `METHODOLOGY.md` first.** Every simulation should route through "
               "`sim_core.py`; hand-rolled simulators have drifted silently twice.\n")
    for title, files in GROUPS:
        rows = [(f, summary(f)) for f in files
                if os.path.exists(f) and f not in UNPUBLISHED]
        if not rows:
            continue
        out.append(f"\n## {title}\n")
        for f, s in rows:
            seen.add(f)
            out.append(f"- **`{f}`** — {s}")
    rest = sorted(set(glob.glob("check_*.py")) - seen - UNPUBLISHED)
    if rest:
        out.append("\n## Other / older investigations\n")
        for f in rest:
            out.append(f"- `{f}` — {summary(f)}")
    io.open("SCRIPTS.md", "w", encoding="utf-8").write("\n".join(out) + "\n")
    print(f"wrote SCRIPTS.md  ({len(seen) + len(rest)} scripts)")


if __name__ == "__main__":
    main()

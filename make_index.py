"""
make_index.py
=============
Regenerates SCRIPTS.md from the one-line summary in each script's docstring.

The docstrings are the real documentation in this repo -- each states a
hypothesis, a prior, and what would falsify it. This just makes them findable.
Re-run after adding a script:  python make_index.py
"""
